#!/usr/bin/env node
// Copies the help articles and their search into the Edge Functions, which
// cannot import from the web app:
//
//   apps/web/src/app/help/articles.ts + search.ts
//     → supabase/functions/_shared/help-articles.ts
//
// Run it after changing an article: node tools/sync-help.mjs
// A test (help/search.node-spec.ts) fails when the copy is out of date.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const COPY = `${root}supabase/functions/_shared/help-articles.ts`;

export function buildCopy() {
  const articles = readFileSync(
    `${root}apps/web/src/app/help/articles.ts`,
    'utf8',
  ).replace(
    /^import type \{ GuideId \} from '[^']+';\n/m,
    '/** A how-to video on the Help page (its ids live in the web app). */\ntype GuideId = string;\n',
  );
  const search = readFileSync(
    `${root}apps/web/src/app/help/search.ts`,
    'utf8',
  ).replace(
    /^import \{ HELP_ARTICLES, type HelpArticle \} from '\.\/articles';\n/m,
    '',
  );
  return (
    '// GENERATED by tools/sync-help.mjs from apps/web/src/app/help/articles.ts\n' +
    '// and search.ts. Do not edit; change those and run the script.\n\n' +
    articles.trimEnd() +
    '\n\n// ---- search.ts ----\n' +
    search
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(COPY, buildCopy());
  console.log(`wrote ${COPY.slice(root.length)}`);
}
